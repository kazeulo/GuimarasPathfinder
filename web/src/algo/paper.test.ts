// Table 4.2 (Jordan RoRo Port) differs only in the port's row and column.
const RORO_PORT = [0, 23.95, 30.65, 24.3, 1.3, 8.9, 31.25, 5.4, 26.75, 16.9, 19.8, 16.65, 11.45, 20.2, 9.25]
const TABLE_4_2 = TABLE_4_1.map((row, i) =>
  row.map((v, j) => (i === 0 ? RORO_PORT[j] : j === 0 ? RORO_PORT[i] : v)),
)

function expectMatrixClose(actual: number[][], expected: number[][]) {
  for (let i = 0; i < 15; i++) {
    for (let j = 0; j < 15; j++) {
      expect(actual[i][j], `cell (${i + 1},${j + 1})`).toBeCloseTo(expected[i][j], 6)
    }
  }
}

describe("the app's distances agree with the SP tables", () => {
  it('Table 4.1: all 225 values for Jordan Wharf', () => {
    expectMatrixClose(engine.floydWarshall(ENTRIES.wharf.graph).dist, TABLE_4_1)
  })

  it('Table 4.2: all 225 values for Jordan RoRo Port', () => {
    expectMatrixClose(engine.floydWarshall(ENTRIES.roro.graph).dist, TABLE_4_2)
  })
})
